-- ── RPCs de busca semântica (antiga 028, corrigida) ────────
-- security invoker: a RLS das bases vale para quem chama.
create or replace function public.buscar_exercicios_rag(
  query_embedding extensions.vector(1024),
  filtro_equipamento text[],
  filtro_nivel text[],
  limite int default 20
)
returns table (
  id uuid,
  nome text,
  grupo_primario text,
  grupo_secundario text,
  equipamento text,
  nivel text,
  tipo_movimento text,
  padrao_series jsonb,
  similaridade float
)
language sql stable
set search_path = public, extensions
as $$
  select id, nome, grupo_primario, grupo_secundario, equipamento, nivel,
         tipo_movimento, padrao_series,
         1 - (embedding <=> query_embedding) as similaridade
  from base_exercicios
  where embedding is not null
    and equipamento = any(filtro_equipamento)
    and nivel = any(filtro_nivel)
  order by embedding <=> query_embedding
  limit limite;
$$;

