-- Tabelas com usuario_id: cada usuário só lê, cria, altera e apaga as próprias linhas
-- (PROJETO.md, seção 3). (select auth.uid()) é avaliado uma vez por consulta.
do $$
declare
  tabela text;
begin
  foreach tabela in array array[
    'perfis', 'questionarios', 'historico_peso', 'planos_ia_gerados',
    'planos_treino', 'sessoes_treino', 'historico_series_executadas',
    'planos_dieta', 'planos_dieta_editaveis', 'refeicoes_registradas',
    'registro_refeicoes', 'registros_agua', 'receitas_usuario', 'alimentos_favoritos'
  ] loop
    execute format('alter table public.%I enable row level security', tabela);
    execute format('create policy %I on public.%I for select to authenticated using (usuario_id = (select auth.uid()))', tabela || '_ler', tabela);
    execute format('create policy %I on public.%I for insert to authenticated with check (usuario_id = (select auth.uid()))', tabela || '_criar', tabela);
    execute format('create policy %I on public.%I for update to authenticated using (usuario_id = (select auth.uid())) with check (usuario_id = (select auth.uid()))', tabela || '_alterar', tabela);
    execute format('create policy %I on public.%I for delete to authenticated using (usuario_id = (select auth.uid()))', tabela || '_apagar', tabela);
  end loop;
end;
$$;

