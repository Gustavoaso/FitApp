    and (categorias_excluidas is null or categoria != all(categorias_excluidas))
  order by embedding <=> query_embedding
  limit limite;
$$;

create or replace function public.buscar_conhecimento_rag(
  query_embedding extensions.vector(1024),
  filtro_tipo text,
  limite int default 3
)
returns table (
  id bigint,
  tipo text,
  titulo text,
  fonte text,
  conteudo text,
  similaridade float
)
language sql stable
set search_path = public, extensions
as $$
  select id, tipo, titulo, fonte, conteudo,
         1 - (embedding <=> query_embedding) as similaridade
  from base_conhecimento
  where embedding is not null
    and (filtro_tipo is null or tipo = filtro_tipo)
  order by embedding <=> query_embedding
  limit limite;
$$;

