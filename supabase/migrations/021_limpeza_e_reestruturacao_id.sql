-- 1. Exclui todo o lixo e itens antigos (Taco API) que não possuem código de barras.
DELETE FROM public.base_alimentos WHERE codigo_barras IS NULL;

-- 2. Remove a coluna inútil que era usada apenas para mapeamento da TacoAPI
ALTER TABLE public.base_alimentos DROP COLUMN IF EXISTS id_externo;

-- 3. Prepara a mudança estrutural do ID
TRUNCATE TABLE public.alimentos_refeicao CASCADE;

-- 4. Dropa as constraints e altera o ID na tabela principal para Auto-Incremento
ALTER TABLE public.base_alimentos DROP CONSTRAINT base_alimentos_pkey CASCADE;
ALTER TABLE public.base_alimentos DROP COLUMN id;
ALTER TABLE public.base_alimentos ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;

-- 5. Atualiza a tipagem nas tabelas filhas e recria a relação de dependência
ALTER TABLE public.alimentos_refeicao DROP COLUMN alimento_id;
ALTER TABLE public.alimentos_refeicao ADD COLUMN alimento_id BIGINT NOT NULL REFERENCES public.base_alimentos(id) ON DELETE CASCADE;
